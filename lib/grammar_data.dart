// The Grammar deck's curriculum: one grammar point per day, each with three
// hard-coded example sentences taken from Tatoeba (CC BY 2.0 FR. Every
// sentence keeps its contributor and ID for attribution). Unlike the other
// special decks these don't use spaced repetition; the day's lesson is the
// study, and the flashcards are for the games and everything else.

const String kGrammarTrackId = 'grammar';
const String kGrammarDeckName = 'Grammar';

// The grammar curriculum is broken into named sections, each starting on a
// given day and running up to (but not including) the next section's start -
// shown as a header above its first day, both in the deck view's day groups
// and on the study progress path. Add a new entry here as each section's
// lessons are written; the last entry runs through the final grammarPoints
// day.
class GrammarSection {
  final String title;
  final int startDay;
  const GrammarSection({required this.title, required this.startDay});
}

const List<GrammarSection> grammarSections = [
  GrammarSection(title: 'Section 1: The Essentials', startDay: 1),
