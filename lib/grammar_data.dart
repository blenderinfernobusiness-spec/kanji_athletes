  GrammarSection(title: 'Section 4: There Is and I Have', startDay: 50),
  GrammarSection(title: 'Section 5: Sentence Ending Expressions', startDay: 64),
  GrammarSection(title: 'Section 6: Connecting Expressions', startDay: 69),
  GrammarSection(title: 'Section 7: Comparisons and Preferences', startDay: 76),
  GrammarSection(title: 'Section 8: Questions', startDay: 84),
  GrammarSection(title: 'Section 9: Things You Have To Do', startDay: 91),
  GrammarSection(title: 'Section 10: Experiencing, Listing, and Nuance', startDay: 99),
];

// The section a given grammar day falls under, or null if it's before every
// section's start (shouldn't happen once grammarSections starts at day 1).
GrammarSection? grammarSectionForDay(int day) {
  GrammarSection? match;
  for (final section in grammarSections) {
    if (section.startDay <= day && (match == null || section.startDay > match.startDay)) {
      match = section;
    }
  }
  return match;
}

class GrammarSentence {
  final int tatoebaId;
  final String japanese;
  final String english;
  final String contributor;
  // The grammar form inside [japanese] that the fill-in activity blanks out.
  final String target;
  // [japanese] split into word-sized pieces for the sentence builder. Joined
  // back together they must equal [japanese] exactly.
  final List<String> chunks;

  const GrammarSentence({
    required this.tatoebaId,
    required this.japanese,
    required this.english,
    required this.contributor,
    required this.target,
    required this.chunks,
  });
}

// A related grammar form, shown briefly to introduce and compare. Never
// something the learner needs to memorise.
class RelatedForm {
  final String form;
  final String meaning;
  final String note;
  // An optional real-life usage tip, shown collapsed in its own dropdown
  // rather than inline with note. E.g. だ's "people often drop it in
  // conversation" aside.
  final String? tip;

  const RelatedForm({required this.form, required this.meaning, required this.note, this.tip});
}

